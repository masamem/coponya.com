/** Plain-HTML rendering for build-time prerendering (crawlers, no JS). */
/** Inline links in legal text: `[label](/path)` (internal paths only). */
export const legalLinkPattern = /\[([^\]]+)\]\(((?:\/|#)[^)\s]*)\)/g;

/** Splits text into plain strings and `{ label, href }` links. */
export function legalTextParts(text: string): (string | { label: string; href: string })[] {
  const parts: (string | { label: string; href: string })[] = [];
  let last = 0;
  for (const m of Array.from(text.matchAll(legalLinkPattern))) {
    if (m.index! > last) parts.push(text.slice(last, m.index));
    parts.push({ label: m[1], href: m[2] });
    last = m.index! + m[0].length;
  }
  if (last < text.length) parts.push(text.slice(last));
  return parts;
}

/** Plain text with link markup removed (for meta descriptions etc.). */
export function legalPlainText(text: string): string {
  return text.replace(legalLinkPattern, "$1");
}

export function legalPageHtml(page: LegalPage, escape: (s: string) => string) {
  const inline = (t: string) => legalTextParts(t).map(p => typeof p === "string" ? escape(p) : `<a href="${escape(p.href)}">${escape(p.label)}</a>`).join("");
  return page.sections.map(([heading, blocks]) =>
    `<section>${heading ? `<h2>${escape(heading)}</h2>` : ""}${blocks.map(b => Array.isArray(b)
      ? `<ul>${b.map(i => `<li>${inline(i)}</li>`).join("")}</ul>`
      : `<p>${inline(b)}</p>`).join("")}</section>`).join("");
}
